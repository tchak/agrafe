//! The contracts a backend relies on, pinned: `fixtures/signing-vectors.json`
//! is what a minter elsewhere checks itself against, and
//! `fixtures/envelope-vectors.json` is what keeps the envelopes backends
//! have stored readable. Each test regenerates the vectors from the inputs
//! below and compares with the file, so a change to the scheme is a
//! deliberate change to the file: `cargo test -p agrafe -- --ignored
//! write_vectors` rewrites both.

use std::collections::BTreeMap;
use std::time::{Duration, UNIX_EPOCH};

use base64::Engine;
use base64::engine::general_purpose::{STANDARD, URL_SAFE_NO_PAD};
use http::Method;
use jiff::Timestamp;
use serde_json::{Value, json};
use uuid::Uuid;

use crate::blob::envelope::{Envelope, SealedRepresentation};
use crate::blob::urls::encode_segment;
use crate::blob::{Rendered, RepresentationState, ScanState};
use crate::classify::Category;
use crate::config::SigningConfig;
use crate::signing::Signer;
use agrafe_crypto::streaming::{HEADER_LEN, Header};

const SIGNING: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../fixtures/signing-vectors.json"
);
const ENVELOPE: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../fixtures/envelope-vectors.json"
);

const KEY: [u8; 32] = [1u8; 32];
const BLOB_ID: &str = "0199f6a0-5b2c-7c3d-8e4f-0a1b2c3d4e5f";

fn signer() -> Signer {
    let config: SigningConfig = serde_json::from_value(json!({
        "current_key": "k1",
        "keys": {"k1": STANDARD.encode(KEY)},
        "window": "1h",
    }))
    .unwrap();
    Signer::from_config(&config).unwrap()
}

/// The query string of a representation URL, as `urls::mint` builds it:
/// `application/x-www-form-urlencoded` over the parameters sorted by name.
fn query_string(query: &BTreeMap<&str, &str>) -> String {
    let mut q = form_urlencoded::Serializer::new(String::new());
    for (k, v) in query {
        q.append_pair(k, v);
    }
    q.finish()
}

fn signing_vectors() -> Value {
    let signer = signer();
    let envelope = sample_envelope().encode();

    // Tokens: method, expiry and tail, with HEAD signing as GET.
    let tails = [
        format!("/{BLOB_ID}"),
        format!("/{BLOB_ID}/original/photo.jpg"),
        format!("/{BLOB_ID}/original/photo%20%C3%A9t%C3%A9.jpg?disposition=attachment"),
        format!("/{BLOB_ID}/thumbnail/photo.jpg?e={envelope}&wait=5000"),
    ];
    let mut sign = Vec::new();
    for (method, expires, tail) in [
        (Method::GET, 2_000_000_000u64, &tails[0]),
        (Method::PUT, 2_000_000_000, &tails[0]),
        (Method::GET, 2_000_000_000, &tails[1]),
        (Method::HEAD, 2_000_000_000, &tails[1]),
        (Method::GET, 2_000_000_000, &tails[2]),
        (Method::GET, 1_800_000_000, &tails[3]),
    ] {
        let token = signer.sign(&method, expires, tail);
        sign.push(json!({
            "method": method.as_str(),
            "expires": expires,
            "tail": tail,
            "token": token,
            "url": format!("https://files.example/blobs/{token}{tail}"),
        }));
    }

    // Expiry: rounded up to the window, then the TTL.
    let expiry: Vec<Value> = [
        (3_601u64, 600u64),
        (7_199, 600),
        (7_200, 600),
        (7_201, 86_400),
    ]
    .into_iter()
    .map(|(now, ttl)| {
        json!({
            "now": now,
            "window": 3600,
            "ttl": ttl,
            "expires": signer.expiry_for(Duration::from_secs(ttl), UNIX_EPOCH + Duration::from_secs(now)),
        })
    })
    .collect();

    // The filename as a path segment, and query parameters as a string.
    let segments: Vec<Value> = [
        "photo.jpg",
        "a b/c?d#e.png",
        "été.pdf",
        "100%.txt",
        "x~y_z-1",
    ]
    .into_iter()
    .map(|f| json!({"filename": f, "segment": encode_segment(f)}))
    .collect();
    let queries: Vec<Value> = [
        BTreeMap::from([("wait", "5000")]),
        BTreeMap::from([("filename", "été x.pdf"), ("disposition", "attachment")]),
        BTreeMap::from([
            ("wait", "5000"),
            ("e", envelope.as_str()),
            ("disposition", "inline"),
        ]),
    ]
    .into_iter()
    .map(|q| json!({"query": q, "string": query_string(&q)}))
    .collect();

    json!({
        "_comment": "Generated by crates/agrafe/src/vectors.rs; a minter elsewhere checks itself against this. Message: METHOD \"\\n\" expires \"\\n\" tail; token: v1.<key_id>.<expires>.<base64url nopad of HMAC-SHA256>; HEAD signs as GET.",
        "key_id": "k1",
        "key": STANDARD.encode(KEY),
        "sign": sign,
        "expiry": expiry,
        "segments": segments,
        "queries": queries,
    })
}

fn sample_envelope() -> Envelope {
    let mut header = [0u8; HEADER_LEN];
    header[0] = HEADER_LEN as u8;
    for (i, b) in header[1..].iter_mut().enumerate() {
        *b = i as u8;
    }
    Envelope {
        kek_id: "kek1".into(),
        wrapped_key: (0..60u8).collect(),
        header: Header::parse(&header).unwrap(),
        chunk_size: 256 * 1024,
        size: 4_200_000_123,
        checksum: [0xab; 32],
        content_type: "image/jpeg".into(),
        category: Category::Image,
        scan_state: ScanState::Clean,
        uploaded_at: Some("2026-10-16T08:44:26Z".parse().unwrap()),
        thumbnail: SealedRepresentation {
            state: RepresentationState::Ready,
            variant_version: Some(1),
            rendered: Some(Rendered {
                sha256: [0xcd; 32],
                size: 12_345,
            }),
        },
        preview: SealedRepresentation {
            state: RepresentationState::Unavailable,
            variant_version: Some(1),
            rendered: None,
        },
    }
}

fn envelope_json(e: &Envelope) -> Value {
    let rep = |r: &SealedRepresentation| {
        json!({
            "state": r.state.as_str(),
            "variant_version": r.variant_version,
            "sha256": r.rendered.map(|r| hex(&r.sha256)),
            "size": r.rendered.map(|r| r.size),
        })
    };
    json!({
        "encoded": e.encode(),
        "kek_id": e.kek_id,
        "wrapped_key": URL_SAFE_NO_PAD.encode(&e.wrapped_key),
        "header": hex(e.header.as_bytes()),
        "chunk_size": e.chunk_size,
        "size": e.size,
        "checksum": hex(&e.checksum),
        "content_type": e.content_type,
        "category": e.category.as_str(),
        "scan_state": e.scan_state.as_str(),
        "uploaded_at": e.uploaded_at.map(|t| t.to_string()),
        "thumbnail": rep(&e.thumbnail),
        "preview": rep(&e.preview),
    })
}

fn envelope_vectors() -> Value {
    let full = sample_envelope();
    let mut bare = sample_envelope();
    bare.uploaded_at = None;
    bare.scan_state = ScanState::Skipped;
    bare.content_type = "application/octet-stream".into();
    bare.category = Category::Other;
    bare.thumbnail = SealedRepresentation {
        state: RepresentationState::Pending,
        variant_version: None,
        rendered: None,
    };
    bare.preview = SealedRepresentation {
        state: RepresentationState::Disabled,
        variant_version: None,
        rendered: None,
    };
    json!({
        "_comment": "Generated by crates/agrafe/src/vectors.rs; the envelope format, version 1, as blob::envelope documents it. Backends store envelopes, so a later version must still decode these.",
        "envelopes": [envelope_json(&full), envelope_json(&bare)],
    })
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn read(path: &str) -> Value {
    let text = std::fs::read_to_string(path).unwrap_or_else(|e| panic!("{path}: {e}"));
    serde_json::from_str(&text).unwrap()
}

#[test]
fn signing_vectors_hold() {
    let expected = read(SIGNING);
    let actual = signing_vectors();
    assert_eq!(actual, expected, "the signing scheme changed; see the file");
    // And every token in the file verifies, for its method and tail, with
    // HEAD accepted for GET. Shortly before it expires: the server also
    // refuses a token that outlives `signing.ttl.max`.
    let signer = signer();
    for case in expected["sign"].as_array().unwrap() {
        let method: Method = case["method"].as_str().unwrap().parse().unwrap();
        let tail = case["tail"].as_str().unwrap();
        let token = case["token"].as_str().unwrap();
        let now = UNIX_EPOCH + Duration::from_secs(case["expires"].as_u64().unwrap() - 60);
        assert_eq!(signer.verify(token, &method, tail, now), Ok(()), "{tail}");
        if method == Method::GET {
            assert_eq!(signer.verify(token, &Method::HEAD, tail, now), Ok(()));
        }
        assert!(
            signer
                .verify(token, &method, &format!("{tail}x"), now)
                .is_err()
        );
    }
}

#[test]
fn envelope_vectors_hold() {
    let expected = read(ENVELOPE);
    assert_eq!(
        envelope_vectors(),
        expected,
        "the envelope format changed; bump the version and keep decoding this"
    );
    // The strings in the file decode to what the file says, whatever the
    // encoder does today.
    for case in expected["envelopes"].as_array().unwrap() {
        let decoded = Envelope::decode(case["encoded"].as_str().unwrap()).unwrap();
        let mut as_json = envelope_json(&decoded);
        as_json["encoded"] = case["encoded"].clone();
        assert_eq!(as_json, *case);
    }
}

#[test]
fn sample_envelope_is_a_valid_row() {
    let head = sample_envelope().head(BLOB_ID.parse::<Uuid>().unwrap(), "photo.jpg");
    assert_eq!(
        Envelope::from_head(&head, Timestamp::now()),
        Some(sample_envelope())
    );
}

/// Rewrites both files from the inputs above.
#[test]
#[ignore]
fn write_vectors() {
    for (path, value) in [(SIGNING, signing_vectors()), (ENVELOPE, envelope_vectors())] {
        let mut text = serde_json::to_string_pretty(&value).unwrap();
        text.push('\n');
        std::fs::write(path, text).unwrap();
    }
}
